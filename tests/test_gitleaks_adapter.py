def test_fetch_repo_bare_and_depth_are_real(tmp_path):
    from control_plane.orchestrator.git_fetch import GitFetchError, cleanup_repo, fetch_repo
    repo = history_only_secret_repo(tmp_path / "repo", filler_commits=5)
    fetched = fetch_repo(repo.location, "main", depth=3, bare=True)
    try:
        assert not (Path(fetched.local_path) / ".git").exists(), "not bare: a working tree exists"
        assert (Path(fetched.local_path) / "HEAD").exists()
        assert fetched.commit_sha == repo.tip
        assert git("rev-list", "--count", "HEAD", cwd=fetched.local_path) == "3"
        assert (Path(fetched.local_path) / "shallow").exists()
    finally:
        cleanup_repo(fetched.local_path)
    with pytest.raises(GitFetchError):
        fetch_repo(repo.location, "main", depth=0)
