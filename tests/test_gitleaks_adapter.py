class StubSandbox:
    """Answers with canned tool output; records what it was asked to run and mount."""

    def __init__(self, *, stdout="[]", stderr=REAL_STDERR_CLEAN, exit_code=0):
        self.runs: list[dict] = []
        self.stdout, self.stderr, self.exit_code = stdout, stderr, exit_code

    def run(self, *, command, network_allowlist, max_duration_seconds,
            run_id=None, tmpfs=None, source_mounts=None,
            engagement_id=None, no_network=False):
        self.runs.append({"command": list(command), "source_mounts": dict(source_mounts or {})})
        return SandboxResult(
            exit_code=self.exit_code, stdout=self.stdout, stderr=self.stderr,
            timed_out=False, duration_seconds=0.1,
            network_allowlist=tuple(network_allowlist), image="stub",
        )


def _uid(prefix: str) -> str:
    return f"{prefix}-{uuid.uuid4().hex[:10]}"


def _dispatch(conn, engagement_id, *, target, sandbox, depth=None, ruleset_path=None):
    result = issue_capability(
        conn, engagement_id=engagement_id, capability_id=_uid("CAP"),
        agent_id="fake-worker", action=ACTION, actor="orchestrator",
        constraints={} if depth is None else {"history_depth": depth},
        budget=Budget(max_duration_seconds=60), ttl_seconds=60,
    )
    assert result.issued is True, result.reasons
    proposal_id = _uid("PROP")
    conn.execute(
        text("""
            INSERT INTO action_proposals (proposal_id, engagement_id, agent_id,
                request_idempotency_key, dispatch_state, action, target,
                "authorization", discovery)
            VALUES (:pid, :eid, 'fake-worker', :key, 'queued', :action,
                    CAST(:target AS jsonb), CAST(:auth AS jsonb), CAST(:disc AS jsonb))
        """),
        {
            "pid": proposal_id, "eid": engagement_id, "key": f"key-{proposal_id}",
            "action": ACTION,
            "target": json.dumps({"logical_identity": {"type": "repo", "value": target}}),
            "auth": '{"source": "engagement_scope", "scope_object_id": "SCOPE-1"}',
            "disc": '{"source": "explicit_scope"}',
        },
    )
    return dispatch_code_scan(
        conn, engagement_id=engagement_id, proposal_id=proposal_id,
        capability=result.capability, target=target, actor="orchestrator",
        sandbox=sandbox, ruleset_path=ruleset_path,
    )


def test_the_dimensions_that_are_not_adapter_inputs_are_pinned(tmp_path, engagement_id):
    """Non-adapter fingerprint dimensions (ADR §5): the tip commit, the depth, the pinned
    config. Each is changed alone and must produce a *different* run; the unchanged control
    must be a dedup hit -- so a green result cannot come from the dedup simply never firing."""
    repo = history_only_secret_repo(tmp_path / "repo", filler_commits=2)
    target = repo.scope_value

    with engagement_scope(engagement_id) as conn:
        first = _dispatch(conn, engagement_id, target=target, sandbox=StubSandbox())
        assert first.state == SUCCEEDED, first.reason

        # control: nothing changed -> served from cache
        again = _dispatch(conn, engagement_id, target=target, sandbox=StubSandbox())
        assert again.reason == "dedup_hit" and again.run_id == first.run_id

        # depth alone: a deeper scan sees commits a shallower one did not
        deeper = _dispatch(conn, engagement_id, target=target, sandbox=StubSandbox(), depth=50)
        assert deeper.reason != "dedup_hit" and deeper.run_id != first.run_id

        # the pinned config alone (a different ruleset file, same commit, same depth)
        other = tmp_path / "other.toml"
        other.write_text('[extend]\nuseDefault = true\n\n# a different file\n')
        reruled = _dispatch(
            conn, engagement_id, target=target, sandbox=StubSandbox(), ruleset_path=str(other),
        )
        assert reruled.reason != "dedup_hit" and reruled.run_id != first.run_id

    # the tip commit alone: the branch moved, the scope string did not
    old_tip = repo.tip
    (repo.path / "later.txt").write_text("later\n")
    new_tip = commit(repo.path, "later")
    assert new_tip != old_tip
    with engagement_scope(engagement_id) as conn:
        moved = _dispatch(conn, engagement_id, target=target, sandbox=StubSandbox())
        assert moved.reason != "dedup_hit" and moved.run_id != first.run_id
        recorded = conn.execute(
            text("SELECT execution_context->>'commit_sha' FROM tool_runs WHERE run_id = :r"),
            {"r": moved.run_id},
        ).scalar_one()
        assert recorded == new_tip


def test_the_fetch_is_bare_and_as_deep_as_the_plan_says(tmp_path, engagement_id, monkeypatch):
    """dispatch_code_scan hands the adapter's FETCH_BARE and the plan's depth to fetch_repo."""
