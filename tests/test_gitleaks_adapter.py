def test_an_incomplete_run_is_recorded_failed_and_is_not_served_from_cache(tmp_path, engagement_id):
    """The dispatch half of D55-8: the tool said "no leaks found", exit 0 -- and the run is
    FAILED, so the next identical proposal runs again instead of returning the false all-clear."""
    repo = history_only_secret_repo(tmp_path / "repo")
    broken = StubSandbox(stdout="[]", stderr=REAL_STDERR_DUBIOUS)
    with engagement_scope(engagement_id) as conn:
        first = _dispatch(conn, engagement_id, target=repo.scope_value, sandbox=broken)
        assert first.state == FAILED
        assert first.result.exit_code == 0, "the control: the tool itself reported success"
        audit = conn.execute(
            text("SELECT payload FROM audit_log WHERE subject_id = :r "
                 "AND event_type = 'tool_run.failed'"),
            {"r": first.run_id},
        ).scalar_one()
        assert audit["scan_incomplete_reason"] == "tool_reported_errors"

        second = _dispatch(conn, engagement_id, target=repo.scope_value, sandbox=StubSandbox())
        assert second.reason != "dedup_hit" and second.state == SUCCEEDED

    # and the control for the control: a complete run IS cached
    with engagement_scope(engagement_id) as conn:
        third = _dispatch(conn, engagement_id, target=repo.scope_value, sandbox=StubSandbox())
        assert third.reason == "dedup_hit"


