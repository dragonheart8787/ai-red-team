def test_the_second_review_is_written_into_the_module_as_listed_here():
    assert auth_guard.REVIEWED_REFUSE_2 == B3_REFUSE
    assert set(B3_REFUSE) <= set(auth_guard.BILLING_VARIABLES)
    for name in B3_KEEP:
        reason = auth_guard.REVIEWED_KEEP[name]
        assert reason.strip() and "\n" not in reason, name


def test_the_two_lists_are_disjoint_and_cover_the_scan():
    assert not set(B3_REFUSE) & set(B3_KEEP)
    assert len(B3_FOUND) == len(B3_REFUSE) + len(B3_KEEP) == 145
    assert not set(auth_guard.BILLING_VARIABLES) & set(auth_guard.REVIEWED_KEEP)


def test_the_names_the_review_layer_named_are_refused():
    for name in ("CLAUDE_CODE_CUSTOM_OAUTH_URL", "CLAUDE_CODE_HOST_CREDS_FILE",
                 "CLAUDE_CODE_SESSION_ACCESS_TOKEN", "CLAUDE_CODE_OAUTH_REFRESH_TOKEN"):
        assert name in B3_REFUSE and name in auth_guard.BILLING_VARIABLES, name


def test_the_second_review_does_not_overlap_the_first():
    first = (set(auth_guard.DECIDED) | set(auth_guard.SAME_KIND) | set(auth_guard.REVIEWED_REFUSE)
             | {"CLAUDE_CODE_OAUTH_TOKEN", "CLAUDE_CODE_OAUTH_TOKEN_FILE_DESCRIPTOR",
                "ANTHROPIC_WEBHOOK_SIGNING_KEY", "CLAUDE_CODE_USE_POWERSHELL_TOOL",
                "CLAUDE_CODE_USE_COWORK_PLUGINS"})
    assert not B3_FOUND & first
